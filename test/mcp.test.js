import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('real STDIO handshake lists tools and rejects invalid requests without a notification', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'mcp-notifier-discovery-'));
  assert.equal(path.dirname(path.resolve(dir)), path.resolve(os.tmpdir()));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const config = path.join(dir, 'config.json');
  await writeFile(config, JSON.stringify({ profiles: { customNotify: { kind: 'waiting', description: 'Build questions' } } }));
  const client = new Client({ name: 'notifier-test', version: '1' });
  const transport = new StdioClientTransport({ command: process.execPath, args: [fileURLToPath(new URL('../src/cli.js', import.meta.url)), '--config', config], stderr: 'pipe', env: {} });
  t.after(() => client.close());
  await client.connect(transport);
  const { tools } = await client.listTools();
  assert.deepEqual(tools.map(tool => tool.name), ['notify', 'acknowledge_notification', 'list_notifications', 'list_notification_profiles']);
  const invalid = await client.callTool({ name: 'notify', arguments: { kind: 'waiting', message: 'Question' } });
  assert.equal(invalid.isError, true);
  const profiles = await client.callTool({ name: 'list_notification_profiles', arguments: {} });
  const custom = JSON.parse(profiles.content[0].text).profiles.find(p => p.name === 'customNotify');
  assert.equal(custom.kind, 'waiting');
  assert.equal(custom.description, 'Build questions');
  const invalidCustom = await client.callTool({ name: 'notify', arguments: { profile: 'customNotify', message: 'Question' } });
  assert.equal(invalidCustom.isError, true);
  assert.match(invalidCustom.content[0].text, /task_id/);
  await writeFile(config, JSON.stringify({ profiles: { customDone: { kind: 'success', title: 'Custom completion' } } }));
  const reloaded = await client.callTool({ name: 'list_notification_profiles', arguments: {} });
  assert.deepEqual(JSON.parse(reloaded.content[0].text).profiles.map(p => p.name), ['success', 'error', 'waiting', 'info', 'customDone']);
  const listing = await client.callTool({ name: 'list_notifications', arguments: {} });
  assert.deepEqual(JSON.parse(listing.content[0].text).notifications, []);
});
